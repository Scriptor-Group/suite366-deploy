# shellcheck shell=bash
# =============================================================================
# lib/mdns.sh — Avahi/mDNS publishing of *.$DOMAIN so LAN clients resolve the
# appliance without DNS config.
#
# Design: a single self-contained WATCHER service. It polls the current LAN IP
# every 5s and, only when it actually changes, (re)publishes the mDNS names and
# rollout-restarts livekit (whose initContainer re-detects the LAN IP for
# WebRTC media). No NetworkManager/networkd dispatcher hooks: at boot NM fires
# dozens of events (including for every veth/cni iface), and a hook doing
# `systemctl restart` per event trips systemd's start rate-limit and leaves the
# unit permanently dead in `start-limit-hit` (observed on the 2026-07-02 spark
# reboot). Polling is storm-proof, works with any network manager, and offline
# is just "no IP yet — keep waiting".
# =============================================================================

# --- 5. mDNS (Avahi) ---------------------------------------------------------
setup_mdns() {
  log "mDNS (Avahi) — *.$DOMAIN"
  if ! have avahi-daemon; then
    apt-get update -y || warn "apt-get update failed (stale cache?) — install may fail."
    apt-get install -y avahi-daemon avahi-utils \
      || die "avahi install failed (network/apt?)."
  fi
  systemctl enable --now avahi-daemon

  cat > /usr/local/bin/suite366-avahi-aliases.sh <<EOF
#!/usr/bin/env bash
# Generated by install.sh — mDNS watcher: publishes Suite 366 names on the
# CURRENT LAN IP and refreshes them (plus livekit's advertised media IP)
# whenever the IP changes. See lib/mdns.sh for the design rationale.
set -u
NAMES="$DOMAIN drive.$DOMAIN office.$DOMAIN livekit.$DOMAIN turn.$DOMAIN"
STATE=/run/suite366-mdns.ip   # survives service restarts, wiped at boot

current_ip() { ip route get 1.1.1.1 2>/dev/null | awk '{print \$7; exit}'; }
unpublish()  { pkill -P \$\$ -x avahi-publish 2>/dev/null; }
publish()    { local f; for f in \$NAMES; do avahi-publish -a -R "\$f" "\$1" & done; }

trap 'unpublish; exit 0' TERM INT

PUBLISHED=""   # IP the running avahi-publish processes advertise ("" = none)
while :; do
  IP="\$(current_ip)"
  if [ "\${IP:-}" != "\$PUBLISHED" ]; then
    unpublish
    if [ -n "\${IP:-}" ]; then
      echo "suite366-mdns: publishing *.$DOMAIN -> \$IP"
      publish "\$IP"
      # livekit advertises the LAN IP for WebRTC media (rtc.node_ip, rendered
      # by its initContainer): recreate its pod when the LAN IP truly changed
      # so the initContainer re-detects it. Delete the POD by its selector
      # label (app=<name>-livekit) — the label lives on pods, NOT on the
      # Deployment, so a \`rollout restart deploy -l ...\` would silently match
      # nothing. This also self-heals the boot race where the initContainer
      # grabs a transient IP (e.g. WiFi) before the default route settles.
      # \$STATE persists across service restarts so an install.sh re-run does
      # not bounce livekit; at boot the file is absent and the deletion is a
      # harmless no-op if k3s isn't up yet (|| true).
      if [ "\$(cat "\$STATE" 2>/dev/null)" != "\$IP" ]; then
        KUBECONFIG=$KUBECONFIG_PATH k3s kubectl -n $NAMESPACE delete pod \\
          -l app=$RELEASE-livekit --ignore-not-found >/dev/null 2>&1 || true
        echo "\$IP" > "\$STATE"
      fi
    else
      echo "suite366-mdns: no LAN IP (offline?) — waiting"
    fi
    PUBLISHED="\${IP:-}"
  fi
  sleep 5
done
EOF
  chmod +x /usr/local/bin/suite366-avahi-aliases.sh
  fetch "dns/avahi-aliases.service" > /etc/systemd/system/suite366-avahi-aliases.service

  # Drop the dispatcher hooks from previous versions (restart storms at boot —
  # see header). The watcher replaces them.
  rm -f /etc/NetworkManager/dispatcher.d/90-suite366-mdns \
        /etc/networkd-dispatcher/routable.d/90-suite366-mdns

  systemctl daemon-reload
  systemctl reset-failed suite366-avahi-aliases.service 2>/dev/null || true
  systemctl enable suite366-avahi-aliases.service
  systemctl restart suite366-avahi-aliases.service
}
